// ListResources returns generated resource files and counts by kind.
func ListResources(resourcesDir string) (map[string]int, []string, error) {
	counts := make(map[string]int)
	var files []string

	entries, err := os.ReadDir(resourcesDir)
	if err != nil {
		return nil, nil, err
	}

	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".yaml") {
			continue
		}
		files = append(files, e.Name())
		data, err := os.ReadFile(filepath.Join(resourcesDir, e.Name()))
		if err != nil {
			continue
		}
		kind := countKinds(string(data))
		for k, c := range kind {
			counts[k] += c
		}
	}

	sort.Strings(files)
	return counts, files, nil
}

func countKinds(yaml string) map[string]int {
	counts := make(map[string]int)
	for _, line := range strings.Split(yaml, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "kind:") {
			kind := strings.TrimSpace(strings.TrimPrefix(trimmed, "kind:"))
			counts[kind]++
		}
	}
	return counts
}

// ReadResourceFile reads a single YAML file from the resources directory.
func ReadResourceFile(resourcesDir, filename string) ([]byte, error) {
	if strings.Contains(filename, "..") || filepath.IsAbs(filename) {
		return nil, fmt.Errorf("invalid filename: %s", filename)
	}
	return os.ReadFile(filepath.Join(resourcesDir, filename))
}

// MarshalComparisonJSON serialises comparison result.
func MarshalComparisonJSON(v any) ([]byte, error) {
	return json.MarshalIndent(v, "", "  ")
}

// CopyDir copies a directory tree (for test fixtures).
func CopyDir(src, dst string) error {
	return filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if info.IsDir() {
			return os.MkdirAll(target, 0700)
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, data, 0600)
	})
}

// ValidateZipEntries checks all entries in a ZIP for path safety.
func ValidateZipEntries(r io.ReaderAt, size int64) error {
	zr, err := zip.NewReader(r, size)
	if err != nil {
		return err
	}
	for _, f := range zr.File {
		if err := validateZipPath(f.Name); err != nil {
			return err
		}
	}
	return nil
}
