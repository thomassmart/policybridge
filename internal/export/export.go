// Resource order for safe application.
var applyOrder = []string{
	"namespaces.yaml",
	"udns.yaml",
	"vms.yaml",
	"pods.yaml",
	"adminPolicies.yaml",
	"policies.yaml",
}

// YAMLExport generates a single multi-document YAML file.
func YAMLExport(resourcesDir string, metadata ExportMetadata) ([]byte, error) {
	var buf bytes.Buffer

	buf.WriteString("# PolicyBridge export\n")
	buf.WriteString(fmt.Sprintf("# Generated by PolicyBridge %s\n", metadata.PolicyBridgeVersion))
	buf.WriteString(fmt.Sprintf("# vmware-analyzer %s, netpol-analyzer %s\n",
		metadata.VMwareAnalyzerVersion, metadata.NetpolAnalyzerVersion))
	buf.WriteString("#\n")
	buf.WriteString("# This file contains generated Kubernetes/OpenShift Virtualization\n")
	buf.WriteString("# microsegmentation resources in safe application order.\n")
	buf.WriteString("# Review required labels and mappings before applying.\n")
	buf.WriteString("---\n")

	for _, filename := range applyOrder {
		path := filepath.Join(resourcesDir, filename)
		data, err := os.ReadFile(path)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", filename, err)
		}
		if len(data) == 0 {
			continue
		}
		content := strings.TrimSpace(string(data))
		if content != "" {
			buf.WriteString(content)
			buf.WriteString("\n---\n")
		}
	}

	return buf.Bytes(), nil
}

// ExportMetadata holds version and generation info for exports.
type ExportMetadata struct {
	PolicyBridgeVersion    string
	VMwareAnalyzerVersion  string
	NetpolAnalyzerVersion  string
	GenerationConfig       string
	Limitations            []string
	RequiredLabels         []string
}

// KustomizeExport generates a GitOps-ready Kustomize ZIP.
func KustomizeExport(resourcesDir string, comparisonJSON []byte, metadata ExportMetadata) ([]byte, error) {
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)

	readme := generateREADME(metadata)
	if err := addZipEntry(zw, "policybridge-export/README.md", []byte(readme)); err != nil {
		return nil, err
	}

	baseKustomization := `apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - policies/
  - networking/
`
	if err := addZipEntry(zw, "policybridge-export/base/kustomization.yaml", []byte(baseKustomization)); err != nil {
		return nil, err
	}

	policyFiles := []string{"policies.yaml", "adminPolicies.yaml"}
	for _, pf := range policyFiles {
		src := filepath.Join(resourcesDir, pf)
		data, err := os.ReadFile(src)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return nil, err
		}
		if len(data) > 0 {
			entry := fmt.Sprintf("policybridge-export/base/policies/%s", pf)
			if err := addZipEntry(zw, entry, data); err != nil {
				return nil, err
			}
		}
	}

	networkFiles := []string{"namespaces.yaml", "udns.yaml", "vms.yaml", "pods.yaml"}
	for _, nf := range networkFiles {
		src := filepath.Join(resourcesDir, nf)
		data, err := os.ReadFile(src)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return nil, err
		}
		if len(data) > 0 {
			entry := fmt.Sprintf("policybridge-export/base/networking/%s", nf)
			if err := addZipEntry(zw, entry, data); err != nil {
				return nil, err
			}
		}
	}

	overlays := []string{"development", "test", "production"}
	for _, env := range overlays {
		overlayKust := fmt.Sprintf(`apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../../base
# Placeholder: add environment-specific patches here
# patches:
#   - path: patches.yaml
`)
		entry := fmt.Sprintf("policybridge-export/overlays/%s/kustomization.yaml", env)
		if err := addZipEntry(zw, entry, []byte(overlayKust)); err != nil {
			return nil, err
		}
	}

	summary := generateMigrationSummary(metadata)
	if err := addZipEntry(zw, "policybridge-export/reports/migration-summary.md", []byte(summary)); err != nil {
		return nil, err
	}

	if comparisonJSON != nil {
		if err := addZipEntry(zw, "policybridge-export/reports/connectivity-comparison.json", comparisonJSON); err != nil {
			return nil, err
		}
	}

	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func addZipEntry(zw *zip.Writer, name string, data []byte) error {
	if err := validateZipPath(name); err != nil {
		return err
	}
	w, err := zw.Create(name)
	if err != nil {
		return err
	}
	_, err = w.Write(data)
	return err
}

// validateZipPath prevents Zip Slip attacks.
func validateZipPath(name string) error {
	clean := filepath.Clean(name)
	if filepath.IsAbs(clean) {
		return fmt.Errorf("zip slip: absolute path %s", name)
	}
	if strings.HasPrefix(clean, "..") {
		return fmt.Errorf("zip slip: path traversal %s", name)
	}
	parts := strings.Split(clean, string(filepath.Separator))
	for _, p := range parts {
		if p == ".." {
			return fmt.Errorf("zip slip: path traversal in %s", name)
		}
	}
	return nil
}

func generateREADME(meta ExportMetadata) string {
	var b strings.Builder
	b.WriteString("# PolicyBridge Export\n\n")
	b.WriteString("Generated Kubernetes/OpenShift Virtualization microsegmentation resources.\n\n")
	b.WriteString("## Versions\n\n")
	b.WriteString(fmt.Sprintf("- PolicyBridge: %s\n", meta.PolicyBridgeVersion))
	b.WriteString(fmt.Sprintf("- vmware-analyzer: %s\n", meta.VMwareAnalyzerVersion))
	b.WriteString(fmt.Sprintf("- netpol-analyzer: %s\n\n", meta.NetpolAnalyzerVersion))
	b.WriteString("## Structure\n\n")
	b.WriteString("```\n")
	b.WriteString("policybridge-export/\n")
	b.WriteString("  base/           Generated resources\n")
	b.WriteString("  overlays/       Environment overlays (placeholders)\n")
	b.WriteString("  reports/        Migration summary and comparison\n")
	b.WriteString("```\n\n")
	b.WriteString("## Apply\n\n")
	b.WriteString("```bash\n")
	b.WriteString("kubectl apply -k overlays/development/\n")
	b.WriteString("```\n\n")
	if len(meta.Limitations) > 0 {
		b.WriteString("## Limitations\n\n")
		for _, l := range meta.Limitations {
			b.WriteString(fmt.Sprintf("- %s\n", l))
		}
	}
	return b.String()
}

